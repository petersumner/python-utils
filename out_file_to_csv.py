"""
Convert an out file generated by SQL/MP to a CSV file.
Column lengths are determined using the dashed line under the header row.

Input file layout:

COL1     COL2 COL3
-------- ---- -------

00000000 0    000
00000000 00   0000
...

--- X row(s) selected.

"""
import argparse
import csv
import os
import re

def parse_args(argv=None):
  p = argparse.ArgumentParser(description='Convert a SQL/MP out file to CSV file.')
  p.add_argument('file', help='Path to data file.')
  p.add_argument('--outdir', default='.', help='Directory for the CSV output (default: current dir)')
  p.add_argument('--delimiter', default=',',
                 choices=[',', '\\t', '|', ';'],
                 help="Delimiter options for CSV: ',', '\t', '|', ';' (default: ',')")
  p.add_argument('--padding', action='store_true', help='Preserve whitespace padding from input file.')
  args = p.parse_args(argv)
  if not os.path.isfile(args.file):
    p.error('file not found: {args.file}')
  return args

if __name__ == '__main__':
  args = parse_args()
  os.makedirs(args.outdir, exist_ok=True)

  with open(args.file, 'r', encoding='utf-8') as file:
    lines = [lines.rstrip('\r\n') for line in file if line.strip()]

  # Second line of the file is made up of dashed lines separated by spaces where each is
  # the size of one column
  col_slices = [slice(m.start(), m.end()) for m in re.finditer(r'-+', lines[1])]

  rows = []
  for n, line in enumerate(lines):
    # Skip the dashed line and the trailer line
    if n == 1 or re.match(r'--- \d+ row\(s\) selected\.', line):
      continue
    if args.padding:
      rows.append([line[s] for s in col_slices])
    else:
      rows.append([line[s].strip() for s in col_slices])

  with open(os.path.join(args.outdir, args.file+'.csv'), 'w', newline='', encoding='utf-8') as out:
    delimiter = '\t' if args.delimiter == '\\t' else args.delimiter
    writer = csv.writer(out, delimiter=delimiter)
    writer.writerows(rows)